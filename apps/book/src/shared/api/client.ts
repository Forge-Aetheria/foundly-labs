import { request, type RequestDocument, type Variables } from 'graphql-request';
import type { TypedDocumentNode } from '@graphql-typed-document-node/core';
import { fail, ok, type ActionResult, type ErrorCode } from '../types/result';
import { errorMessage } from './error-surface';
import { emitUnauthenticated } from './notify-unauthenticated';
import { env } from '../../env';

/**
 * Typed GraphQL transport for the Foundly API (feature 008; feature 011; feature
 * 024 — SPA). Runs in the browser: the endpoint comes from `VITE_API_URL` and
 * the bearer token is supplied by the caller (active Supabase session).
 * - Accepts the documents generated by `graphql-codegen` (`TypedDocumentNode`).
 * - Per-call `Authorization: Bearer <token>` injection — never cached at module scope.
 * - Maps the API error envelope `errors[].extensions.code` to the book `ErrorCode`.
 * - Emits the global unauthenticated signal so the session provider can react.
 */

export function resolveApiUrl(): string | null {
  return env.apiUrl ? env.apiUrl : null;
}

/** Hard budget for a single GraphQL round-trip. */
export const API_REQUEST_TIMEOUT_MS = env.apiRequestTimeoutMs;

/** An abort signal that fires after `ms`, or `undefined` when unsupported. */
function timeoutSignal(ms: number): AbortSignal | undefined {
  return typeof AbortSignal !== 'undefined' && typeof AbortSignal.timeout === 'function'
    ? AbortSignal.timeout(ms)
    : undefined;
}

export interface ApiRequestOptions {
  token?: string | null;
}

interface ExtensionsLike {
  code?: string;
}

interface GraphQLErrorLike {
  message?: string;
  extensions?: ExtensionsLike;
}

interface ClientErrorLike {
  response?: { errors?: GraphQLErrorLike[] };
  message?: string;
}

/** Map a GraphQL `extensions.code` to the book `ErrorCode` (contract table). */
export function mapErrorCode(code: string | undefined): ErrorCode | null {
  switch (code) {
    case 'UNAUTHENTICATED':
    case 'FORBIDDEN':
    case 'NOT_FOUND':
    case 'CONFLICT':
    case 'VALIDATION_ERROR':
      return code;
    default:
      return null;
  }
}

/** Extract a typed ActionResult from any thrown GraphQL client error. */
export function mapActionError(error: unknown): ActionResult<never> {
  if (error && typeof error === 'object') {
    const err = error as ClientErrorLike;
    const first = err.response?.errors?.[0];
    if (first?.extensions?.code) {
      const code = mapErrorCode(first.extensions.code);
      if (code) {
        if (code === 'UNAUTHENTICATED') {
          emitUnauthenticated();
        }
        // Never leak the raw provider message (English/technical) to the UI.
        return fail(code, errorMessage(code));
      }
    }
  }
  return fail('STATE_ERROR', errorMessage('STATE_ERROR'));
}

/**
 * Execute a generated GraphQL document against the Foundly API and coerce the
 * result into an `ActionResult<T>`. Failures never throw; they map to typed errors.
 */
export async function apiRequest<TResult, TVariables extends Variables = Variables>(
  document: TypedDocumentNode<TResult, TVariables>,
  variables: TVariables,
  options: ApiRequestOptions = {},
): Promise<ActionResult<TResult>> {
  const url = resolveApiUrl();
  if (!url) {
    return fail('STATE_ERROR', 'La API no está configurada.');
  }
  const requestHeaders: Record<string, string> = { 'Content-Type': 'application/json' };
  if (options.token) {
    requestHeaders.Authorization = `Bearer ${options.token}`;
  }
  try {
    const graphqlDocument: RequestDocument = document;
    const data = await request<TResult, Variables>({
      url: `${url.replace(/\/+$/, '')}/graphql`,
      document: graphqlDocument,
      variables,
      requestHeaders,
      signal: timeoutSignal(env.apiRequestTimeoutMs),
    });
    return ok(data);
  } catch (error) {
    return mapActionError(error);
  }
}
